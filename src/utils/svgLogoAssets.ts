interface CachedLogoDataUrl {
  dataUrl: string;
  widthMm: number;
  heightMm: number;
  aspectRatio: number;
}

const logoCache = new Map<string, CachedLogoDataUrl>();

/**
 * Converts an SVG XML string into a high-resolution PNG Data URL for jsPDF.
 */
export async function convertSvgToHighResDataUrl(
  svgXml: string,
  targetHeightMm: number,
  viewBoxW = 100,
  viewBoxH = 100,
  scale = 4
): Promise<CachedLogoDataUrl> {
  const cacheKey = `${svgXml.slice(0, 30)}_${targetHeightMm}_${scale}`;
  if (logoCache.has(cacheKey)) {
    return logoCache.get(cacheKey)!;
  }

  // Parse viewBox from SVG string if possible
  const vbMatch = svgXml.match(/viewBox=["']([0-9.\s]+)["']/i);
  let aspect = viewBoxW / viewBoxH;
  if (vbMatch && vbMatch[1]) {
    const parts = vbMatch[1].trim().split(/\s+/).map(Number);
    if (parts.length === 4 && parts[2] > 0 && parts[3] > 0) {
      aspect = parts[2] / parts[3];
    }
  }

  const calculatedWidthMm = targetHeightMm * aspect;
  const canvasWidthPx = Math.round(calculatedWidthMm * 10 * scale);
  const canvasHeightPx = Math.round(targetHeightMm * 10 * scale);

  return new Promise((resolve) => {
    try {
      const img = new Image();
      const blob = new Blob([svgXml], { type: 'image/svg+xml;charset=utf-8' });
      const url = URL.createObjectURL(blob);

      img.onload = () => {
        const canvas = document.createElement('canvas');
        canvas.width = canvasWidthPx;
        canvas.height = canvasHeightPx;
        const ctx = canvas.getContext('2d');
        if (ctx) {
          ctx.clearRect(0, 0, canvasWidthPx, canvasHeightPx);
          ctx.drawImage(img, 0, 0, canvasWidthPx, canvasHeightPx);
          const dataUrl = canvas.toDataURL('image/png', 1.0);
          URL.revokeObjectURL(url);

          const result: CachedLogoDataUrl = {
            dataUrl,
            widthMm: calculatedWidthMm,
            heightMm: targetHeightMm,
            aspectRatio: aspect,
          };
          logoCache.set(cacheKey, result);
          resolve(result);
          return;
        }
        URL.revokeObjectURL(url);
        resolve({ dataUrl: '', widthMm: calculatedWidthMm, heightMm: targetHeightMm, aspectRatio: aspect });
      };

      img.onerror = () => {
        URL.revokeObjectURL(url);
        resolve({ dataUrl: '', widthMm: calculatedWidthMm, heightMm: targetHeightMm, aspectRatio: aspect });
      };

      img.src = url;
    } catch {
      resolve({ dataUrl: '', widthMm: calculatedWidthMm, heightMm: targetHeightMm, aspectRatio: aspect });
    }
  });
}
