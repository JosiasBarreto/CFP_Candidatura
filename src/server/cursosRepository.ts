let cachedUpstreamCursos: CursoRecord[] | null = null;
let lastUpstreamCheck = 0;

export async function obterCursosOficiais(payload: Record<string, any> = {}): Promise<CursoRecord[]> {
  const upstreamUrl = process.env.UPSTREAM_CURSO_API_URL || 'http://192.168.100.141:5000/curso/busca';
  const now = Date.now();

  // Tenta obter da API upstream se o cache tiver mais de 60 segundos
  if (!cachedUpstreamCursos || now - lastUpstreamCheck > 60_000) {
    lastUpstreamCheck = now;
    try {
      const response = await axios.post(upstreamUrl, payload, { timeout: 1500 });
      if (Array.isArray(response.data) && response.data.length > 0) {
        cachedUpstreamCursos = response.data;
      }
    } catch {
      // Caso o servidor interno 192.168.100.141:5000 não esteja acessível a partir da rede atual,
      // utiliza o repositório oficial sincronizado no backend.
    }
  }

  const lista = cachedUpstreamCursos || CURSOS_DATABASE;

  if (payload && payload.ano_execucao) {
    const filtrados = lista.filter((c) => Number(c.ano_execucao) === Number(payload.ano_execucao));
    return filtrados.length > 0 ? filtrados : lista;
  }

  return lista;
}
